driverInitName = component.createStringSymbol("driverInitName", None)
driverInitName.setVisible(False)
driverInitName.setReadOnly(True)

managedComment = component.createCommentSymbol("managedComment", None)
managedComment.setLabel('Library settings are managed through the Graphics Composer Tool.')
managedComment.setVisible(True)

managedComment2 = component.createCommentSymbol("managedComment2", None)
managedComment2.setLabel('This tool can be launched through the Tools->Graphics Composer option.')
managedComment2.setVisible(True)

useAutoGeneratedCode = component.createBooleanSymbol("useAutoGeneratedCode", None)
useAutoGeneratedCode.setVisible(False)

settingsMenu = component.createMenuSymbol("harmonySettings", None)
settingsMenu.setLabel("MCC Harmony Settings")

enablePerformanceMetrics = component.createBooleanSymbol("enablePerformanceMetrics", settingsMenu)
enablePerformanceMetrics.setLabel("Enable Performance Metrics?")
enablePerformanceMetrics.setDefaultValue(False)
enablePerformanceMetrics.setDescription("Enables collection and reporting of performance metrics for the graphics library.")
enablePerformanceMetrics.setDependencies(onEnablePerformanceMetricsChanged, ["enablePerformanceMetrics"])

libraryTaskPeriod = component.createIntegerSymbol("libraryTaskPeriod", enablePerformanceMetrics)
libraryTaskPeriod.setLabel("GFX library update interval (ms)")
libraryTaskPeriod.setDefaultValue(10)
libraryTaskPeriod.setMin(0)
libraryTaskPeriod.setMax(1000)
libraryTaskPeriod.setDescription("Maximum update interval in ms.<br>"
                                 "0 - will update the GUI as fast as possible.<br>"
                                 "10 will run at 100 frames/second max.")
libraryTaskPeriod.setVisible(False)

periodUsageMonitorOutput = component.createIntegerSymbol("periodUsageMonitorOutput", enablePerformanceMetrics)
periodUsageMonitorOutput.setLabel("Usage Monitor Output period (seconds)")
periodUsageMonitorOutput.setDefaultValue(1)
periodUsageMonitorOutput.setMin(1)
periodUsageMonitorOutput.setMax(60)
periodUsageMonitorOutput.setDescription("The interval usage metrics is calculated and updated (seconds).")
periodUsageMonitorOutput.setVisible(False)

enableUsageMonitorPrint = component.createBooleanSymbol("enableUsageMonitorPrint", enablePerformanceMetrics)
enableUsageMonitorPrint.setLabel("Print Metrics?")
enableUsageMonitorPrint.setDefaultValue(True)
enableUsageMonitorPrint.setDescription("Prints the performance metrics to the console. Requires STDIO.")
enableUsageMonitorPrint.setVisible(False)

enableInputEvents = component.createBooleanSymbol("enableInputEvents", enablePerformanceMetrics)
enableInputEvents.setLabel("Enable Input Event Interface?")
enableInputEvents.setDefaultValue(True)
enableInputEvents.setDescription("Indicates that the library should interface with the Input System Service for input events.")
enableInputEvents.setVisible(False)