/* =================================================
 *  Look-up table driver 
 * -------------------------------------------------
 *  This code is tailored to the LUT data above,
 *  and is ported from the display manufacturer's
 *  example code. The original code is displayed
 *  for reference.
 * 
 *  API info is in the .h file. */
uint8_t AMP_lightDark_toggle = 0;
void AMP_UC8253_send_lut(GFX_Disp_Intf intf, const uint8_t *lut) 
{
    NOP(); NOP(); NOP();
        
    //lutc	VCOM
//    SPI_SendCmd(0x20);
//    for (count = 0; count < 42; count++)
//        SPI_SendData(lut[count]);
    GFX_Disp_Intf_WriteCommandParm(intf, 0x20,
                        (uint8_t *)&lut[0], (42 - 0));

    //lutbb	
//    SPI_SendCmd(0x24);
//    for (count = 168; count < 210; count++)
//        SPI_SendData(lut[count]);
    GFX_Disp_Intf_WriteCommandParm(intf, 0x24,
                        (uint8_t *)&lut[168], (210 - 168));

    //lutww 
//    SPI_SendCmd(0x21);
//    for (count = 42; count < 84; count++)
//        SPI_SendData(lut[count]);
    GFX_Disp_Intf_WriteCommandParm(intf, 0x21,
                        (uint8_t *)&lut[42], (84 - 42));

    if (AMP_lightDark_toggle == 0) 
    {
        NOP(); NOP(); NOP();
        
        //lutbw 
//        SPI_SendCmd(0x22);
//        for (count = 84; count < 126; count++)
//            SPI_SendData(lut[count]);
        GFX_Disp_Intf_WriteCommandParm(intf, 0x22,
                        (uint8_t *)&lut[84], (126 - 84));

        //lutwb    
//        SPI_SendCmd(0x23);
//        for (count = 126; count < 168; count++)
//            SPI_SendData(lut[count]);
        GFX_Disp_Intf_WriteCommandParm(intf, 0x23,
                        (uint8_t *)&lut[126], (168 - 126));
#if !DRV_GFX_DO_NOT_TOGGLE_LUT
        AMP_lightDark_toggle = 1;
#endif
    }
    else 
    {
        NOP(); NOP(); NOP();
        
        //lutbw 
//        SPI_SendCmd(0x23);
//        for (count = 84; count < 126; count++)
//            SPI_SendData(lut[count]);
        GFX_Disp_Intf_WriteCommandParm(intf, 0x23,
                        (uint8_t *)&lut[84], (126 - 84));

        //lutwb    
//        SPI_SendCmd(0x22);
//        for (count = 126; count < 168; count++)
//            SPI_SendData(lut[count]);
        GFX_Disp_Intf_WriteCommandParm(intf, 0x22,
                        (uint8_t *)&lut[126], (168 - 126));
#if !DRV_GFX_DO_NOT_TOGGLE_LUT
        AMP_lightDark_toggle = 0;
#endif
    }
}
